"""(JIANT 0.9.12) The interactive manual's generated half (web/manual): the navigation chains, read from the firmware
through tools/gen_nav_map.py's own data model (parse(), its rules / layers / combos (English: 3c-1 task 10b), COND), and
the firmware's real screens (tests/ui_render.c's renders) that the manual shows.

  python3 tools/gen_manual.py [RENDERS]   web/manual/nav.js, and web/manual/shots/*.png copied from RENDERS
                                          (default build/ui_new/ACID: run tests/run_tests.sh, or ui_render alone)
  python3 tools/gen_manual.py --check     exit 1 if nav.js differs from what the firmware's chains give, or a screen
                                          the manual names (nav.js or web/manual/data.js) is missing in shots/

The screens are the one skin (AIR's look) in the one palette, ACID (ACID FM 0.3; until then AIR in JIANT's palette). Only the ones the manual names are
copied (the page each nav pill opens, PAGE_SHOT below, and every shot:'name' in data.js); stale ones are removed.
"""
import json
import re
import shutil
import sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / 'tools'))
import gen_nav_map as nav  # noqa: E402

OUT = R / 'web/manual'
SHOTS = OUT / 'shots'

# the screen each page of the map opens (tests/ui_render.c's scene names; the breadcrumb of each checked by hand)
PAGE_SHOT = {
    'HOME': {'TRACKS': 'home', 'VISUAL': 'home_visual',   # (ACID FM 3a: was ECO MACROS BEING ROUTES)
             'GEN 1': 'gen_explore', 'GEN 2': 'gen_parts', 'GEN 3': 'gen_lead'},
    'CE_SYN': {'SOUND': 'edit_analog_1', 'TONE': 'edit_analog_2', 'VOICE': 'edit_analog_3', 'FILTER': 'edit_phase_3',
               'MORE': 'edit_analog_more'},   # (3b task 4: a synth's EDIT on the ux pages)
    'CE_FM6': {'SOUND': 'edit_fm6_1', 'OPERATOR': 'edit_fm6_2', 'OP ENV': 'edit_fm6_3', 'MORE': 'edit_fm6_more'},
    'CE_DRM': {'KIT': 'edit_drum_1', 'SOUND': 'edit_drum_2', 'SOUND 2': 'edit_drum_3', 'MORE': 'edit_drum_more'},
    # (3b task 5: FM6's and DRUM-X's EDIT on the ux pages, their creatures gone)
    'SEQ': {'STEPS': 'seq_steps', 'STEP EXTRAS': 'seq_extras', 'PATTERN': 'seq_pattern', 'MORE': 'seq_more'},   # (3c-1 tasks 2-4:
            # STEPS, STEP EXTRAS, PATTERN, MORE on the ux pages; JIANT's STRETCH .. AUTO LIST MORE's rows)
    'FX': {'SENDS': 'fx_1', 'SPACE': 'fx_2', 'MASTER': 'fx_3', 'MORE': 'fx_more'},   # (3b task 8: FX on the ux pages)
    'GLO': {'LIVE': 'glo_live_tricks', 'MIX': 'glo_mix', 'MIDI': 'glo_midi', 'MORE': 'glo_more'},   # (3c-1 task 6: LIVE and MORE
            # on the ux pages; the inherited second LIVE page MORE's RAILS rows; task 7: MIX, the MIXER SENDS GLOBAL SYSTEM gone;
            # task 8: MIDI)
    'ENV': {'AMP': 'env_1', 'ENV TO': 'env_2'},   # (3b task 6: ENV, SCL, ARP on the ux pages)
    'LFO': {'LFO': 'lfo_1', 'DEST': 'lfo_2', 'MOD MATRIX': 'lfo_3', 'MORE': 'lfo_more'},   # (3b task 7: LFO on the ux pages)
    'SCL': {'KEY': 'scl_1', 'CHORD': 'scl_2', 'MORE': 'scl_more'},
    'ARP': {'ARP': 'arp_1', 'ARP 2': 'arp_2'},
    'SAVE': {'SOUND': 'save_sound', 'SONG': 'save_song',   # (3c-2 task 2: SOUND the ux page, USER PRESETS gone; MORE;
             'PROJECTS': 'save_library', 'TOOLS': 'save_tools', 'MORE': 'save_more'},   # task 3: SONG, SECTIONS ARRANGE gone)
}
CHAIN_LABEL = {'CE_SYN': 'SYNTHS', 'CE_FM6': 'FM6', 'CE_DRM': 'DRUM-X'}


def build():
    sec, keys = nav.parse()
    chains = []
    for k in keys:
        shots = PAGE_SHOT.get(k['ce'], PAGE_SHOT.get(k['sec'], {}))
        chains.append(dict(
            sec=k['sec'], ce=k['ce'], label=CHAIN_LABEL.get(k['ce']),
            groups=[g['nm'] for g in k['groups']],
            pages=[dict(name=p['name'], g=p['g'], on=p['i'] == k['default'],
                        cond=nav.is_cond(k['sec'], k['ce'], p['name']), shot=shots.get(p['name'])) for p in k['pages']]))
    T = nav.T
    words = dict(rules=[dict(k=a, t=b, d=c) for a, b, c in T['rules']],
                 layers=[dict(b=b, d=d.replace('**', '')) for b, d in T['layers']],
                 combos=[dict(k=k, d=d) for k, d in T['combos']],
                 hints={s: dict(hold=h[0], sel=h[1]) for s, h in T['hints'].items()},
                 notes=T['notes'])
    data = dict(version=nav.VERSION, sections=sec, chains=chains, words=words)
    return ('// SPDX-License-Identifier: GPL-3.0-only\n'
            '// GENERATED by tools/gen_manual.py from firmware/src/ui_lens.c (via tools/gen_nav_map.py): do not edit\n'
            'window.JNAV = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')


def wanted(navjs):
    names = set(re.findall(r'"shot":"([\w-]+)"', navjs))
    data = (OUT / 'data.js').read_text(encoding='utf-8')
    names |= set(re.findall(r"\bshot:\s*'([\w-]+)'", data))
    for m in re.findall(r"\bshots:\s*\[([^\]]*)\]", data):
        names |= set(re.findall(r"'([\w-]+)'", m))
    return names


def main(argv):
    navjs = build()
    if '--check' in argv:
        bad = []
        if (OUT / 'nav.js').read_text(encoding='utf-8') != navjs:
            bad.append('web/manual/nav.js differs from the firmware chains: run tools/gen_manual.py')
        bad += [f'web/manual/shots/{n}.png missing' for n in sorted(wanted(navjs)) if not (SHOTS / f'{n}.png').exists()]
        for b in bad:
            print('gen_manual:', b)
        sys.exit(1 if bad else 0)
    src = Path(argv[0]) if argv else R / 'build/ui_new/ACID'
    (OUT / 'nav.js').write_text(navjs, encoding='utf-8')
    names = wanted(navjs)
    SHOTS.mkdir(exist_ok=True)
    for f in SHOTS.glob('*.png'):
        if f.stem not in names:
            f.unlink()
    missing = []
    for n in sorted(names):
        s = src / f'{n}.png'
        if s.exists():
            shutil.copy(s, SHOTS / s.name)
        else:
            missing.append(n)
    print(f'gen_manual: nav.js ({len(navjs)} B), {len(names) - len(missing)} screens from {src}')
    if missing:
        sys.exit('gen_manual: no render for ' + ' '.join(missing))


if __name__ == '__main__':
    main(sys.argv[1:])
