"""firmware/src/ux_blend.h: ACID FM's 256-step blend ACID -> SLIDE -> VIOLET -> ACCENT -> QUEUED as native RGB565
(const, in flash). Run by hand after changing the stops; the output is checked in.
  gen_ux_blend.py [OUT.h]"""
import sys
from pathlib import Path

STOPS = [(0xB8, 0xF5, 0x3A), (0x4C, 0xB8, 0xFF), (0xA6, 0x4B, 0xFF), (0xFF, 0x50, 0x3C), (0xFF, 0xC8, 0x3C)]


def blend(i):
    pos = i * 4 / 255.0
    seg = min(int(pos), 3)
    f = pos - seg
    r, g, b = (round(STOPS[seg][k] + (STOPS[seg + 1][k] - STOPS[seg][k]) * f) for k in range(3))
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "firmware" / "src" / "ux_blend.h"
    rows = []
    for r in range(0, 256, 8):
        rows.append("    " + ", ".join("0x%04X" % blend(i) for i in range(r, r + 8)) + ",")
    out.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Copyright (C) 2026 NorfolkHacker */\n"
                   "/* generated by tools/gen_ux_blend.py: UX_BLEND's 256 entries (ux_theme.c) */\n" + "\n".join(rows) + "\n")


main()
