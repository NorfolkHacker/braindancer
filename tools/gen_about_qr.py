"""Print the ABOUT page's QR table (firmware/src/ui_menu.c ABOUT_QR) for a URL: QR version 3 (29 x 29), correction L,
no quiet zone (draw_about_qr draws its own), one row per word, the leftmost module in bit 0.

  python3 tools/gen_about_qr.py https://github.com/NorfolkHacker/braindancer
"""
import sys

try:
    import segno
except ImportError:
    sys.exit("gen_about_qr: the Python package segno is missing (it is in the project's .venv: . .venv/bin/activate)")


def rows(url):
    qr = segno.make_qr(url, version=3, error="l", boost_error=False)
    out = []
    for line in qr.matrix:
        word = 0
        for col, dark in enumerate(line):
            if dark:
                word |= 1 << col
        out.append(word)
    assert len(out) == 29 and all(len(line) == 29 for line in qr.matrix)
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    words = [f"0x{w:08X}u" for w in rows(sys.argv[1])]
    print(f"/* {sys.argv[1]}, QR version 3, correction L, generated by tools/gen_about_qr.py (segno).")
    print(" * One row per word, leftmost module in bit 0; the constant matrix needs no encoder or RAM. */")
    print("static const uint32_t ABOUT_QR[29] = {")
    for i in range(0, 29, 6):
        print("    " + ", ".join(words[i:i + 6]) + ",")
    print("};")


if __name__ == "__main__":
    main()
